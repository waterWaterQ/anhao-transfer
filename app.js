// 检测 WebRTC 实际线路类型（局域网直连 vs 国内跨网直连）
async function detectRouteType() {
  try {
    if (!pc || typeof pc.getStats !== "function") return "";
    const stats = await pc.getStats();
    let activePair = null;
    stats.forEach((report) => {
      if (report.type === "candidate-pair" && (report.selected || report.state === "succeeded")) {
        activePair = report;
      }
    });
    if (!activePair) return "";
    const local = stats.get(activePair.localCandidateId);
    const remote = stats.get(activePair.remoteCandidateId);
    if (local?.candidateType === "host" && remote?.candidateType === "host") {
      return "🏠 局域网极速直连";
    }
    return "🌐 国内跨网点对点直连";
  } catch {
    return "";
  }
}

// 仅清理 WebRTC 连接（发送方保留房间继续等待新连接时使用）
function closePeerConnectionOnly() {
  clearTimeout(stepTimer);
  stepTimer = null;
  clearIdleTimer();
  clearTransferState(true);
  pendingIceCandidates = [];
  remotePeerId = null;

  if (dc) {
    dc.onopen = null;
    dc.onmessage = null;
    dc.onclose = null;
    dc.onerror = null;
    try { dc.close(); } catch {}
    dc = null;
  }
  if (pc) {
    pc.onicecandidate = null;
    pc.ondatachannel = null;
    pc.onconnectionstatechange = null;
    try { pc.close(); } catch {}
    pc = null;
  }
  updateSendControls();
}

// 彻底清理全部会话，回到初始状态
function resetSession(statusMsg = "已断开连接，可重新创建或加入房间") {
  clearTimeout(probeTimer);
  probeTimer = null;
  closePeerConnectionOnly();

  if (signal) {
    signal.onMessage = null;
    signal.onClose = null;
    signal.close();
    signal = null;
  }

  roomTopic = null;
  currentRole = null;
  roomActive = false;
  pendingGuestId = null;

  connectRequestBox.classList.add("hidden");
  createRoomBtn.disabled = false;
  createRoomBtn.textContent = "生成房间并等待对方连接";
  sendCodeInput.disabled = false;
  randomCodeBtn.disabled = false;
  joinRoomBtn.disabled = false;
  receiveCodeInput.disabled = false;

  updateSendControls();
  setStatus("idle", statusMsg, false);
}

// ==================== 原生 WebRTC 建立与事件绑定 ====================

function setupPeerConnection(targetId) {
  closePeerConnectionOnly();
  remotePeerId = targetId;

  pc = new RTCPeerConnection({
    iceServers: APP_CONFIG.iceServers,
  });

  pc.onicecandidate = (event) => {
    if (event.candidate && remotePeerId) {
      sendSignal({
        type: "webrtc-ice",
        to: remotePeerId,
        candidate: event.candidate,
      });
    }
  };

  pc.onconnectionstatechange = () => {
    if (!pc) return;
    const state = pc.connectionState;
    if (state === "failed" || state === "disconnected" || state === "closed") {
      handleChannelLost();
    }
  };

  // 15 秒 WebRTC 打洞超时保护
  clearTimeout(stepTimer);
  stepTimer = setTimeout(() => {
    if (!isChannelOpen()) {
      if (currentRole === "sender") {
        closePeerConnectionOnly();
        pendingGuestId = null;
        createRoomBtn.textContent = "房间已开启，等待对方输入暗号...";
        setStatus("waiting", `点对点打洞超时（可能受对称型防火墙限制），房间已解锁（暗号：${sendCodeInput.value.trim()}）`, true);
        showToast("本次打洞超时，房间已自动解锁");
      } else {
        resetSession("国内点对点直连超时（15秒）：若使用手机 5G 对称网络或开启了代理 TUN，请切换普通宽带/同一 Wi-Fi 后重试");
        showToast("点对点直连超时");
      }
    }
  }, APP_CONFIG.webrtcConnectTimeoutMs);
}

function attachDataChannel(channel) {
  dc = channel;
  dc.binaryType = "arraybuffer";
  dc.bufferedAmountLowThreshold = APP_CONFIG.lowBufferedAmount;

  dc.onopen = async () => {
    clearTimeout(stepTimer);
    stepTimer = null;
    const routeInfo = await detectRouteType();

    if (currentRole === "sender") {
      createRoomBtn.textContent = "已与对方加密直连";
      setStatus("ready", `已建立一对一加密直连 ${routeInfo ? `｜ ${routeInfo}` : ""}`, true);
      updateSendControls();
      resetIdleTimer();
      showToast("直连成功！现在可以发送文件或文字了");
    } else {
      // 接收方建立 P2P 直连后即可关闭信令连接，节省资源
      if (signal) {
        signal.onClose = null;
        signal.close();
        signal = null;
      }
      setStatus("ready", `已建立一对一加密直连 ${routeInfo ? `｜ ${routeInfo}` : "｜ 等待对方发送"}`, true);
      resetIdleTimer();
      showToast("配对成功！等待发送方传文件");
    }
  };

  dc.onmessage = (event) => {
    handleChannelMessage(event.data);
  };

  dc.onclose = () => {
    handleChannelLost();
  };

  dc.onerror = () => {
    handleChannelLost();
  };
}

function handleChannelLost() {
  if (!pc && !dc) return;
  const wasTransferring = isTransferring;

  if (currentRole === "sender" && roomActive) {
    closePeerConnectionOnly();
    pendingGuestId = null;
    createRoomBtn.textContent = "房间已开启，等待对方输入暗号...";
    setStatus(
      wasTransferring ? "error" : "waiting",
      wasTransferring
        ? `传输中断：对方已断开连接（暗号：${sendCodeInput.value.trim()} 仍可等待重连）`
        : `对方已断开，房间已解锁，等待新连接（暗号：${sendCodeInput.value.trim()}）`,
      true
    );
    showToast(wasTransferring ? "对方断线，传输已中断" : "对方已断开连接");
  } else if (currentRole === "receiver") {
    resetSession(wasTransferring ? "传输中断：发送方已断开连接，已清理残余缓存" : "与发送方的连接已断开");
    if (wasTransferring) showToast("发送方断线，传输已中断");
  }
}

async function flushPendingIce() {
  if (!pc || !pc.remoteDescription) return;
  while (pendingIceCandidates.length > 0) {
    const cand = pendingIceCandidates.shift();
    try {
      await pc.addIceCandidate(new RTCIceCandidate(cand));
    } catch {}
  }
}

// ==================== 发送方：创建房间 + 查重 + 1 对 1 锁房 ====================

async function createSenderRoom() {
  const rawCode = sendCodeInput.value.trim();
  if (rawCode.length < APP_CONFIG.minCodeLength) {
    showToast(`暗号至少需要 ${APP_CONFIG.minCodeLength} 位`);
    return;
  }

  if (signal || pc) resetSession("正在重新创建房间...");

  currentRole = "sender";
  createRoomBtn.disabled = true;
  sendCodeInput.disabled = true;
  randomCodeBtn.disabled = true;
  setStatus("waiting", "正在连接国内信令节点...", true);

  try {
    signal = new MqttSignalClient();
    await signal.connect();
  } catch {
    resetSession("无法连接国内信令节点，请检查网络后重试");
    showToast("连接国内信令失败，请检查网络");
    return;
  }

  roomTopic = codeToRoomTopic(rawCode);
  let occupied = false;

  signal.onMessage = (topic, msg) => {
    if (topic !== roomTopic || !msg || msg.from === myClientId) return;
    if (msg.to && msg.to !== myClientId) return;

    // 查重期间如果收到已有房主回复，说明暗号已被占用
    if (!roomActive && msg.type === "room-occupied") {
      occupied = true;
      clearTimeout(probeTimer);
      if (isAutoGeneratedCode && autoRetryCount < 5) {
        autoRetryCount++;
        sendCodeInput.value = generateSafeCode();
        createSenderRoom();
      } else {
        resetSession("该暗号正在被别人使用，请换一个暗号或点“换一个”");
        showToast("暗号已被占用，请更换后再试");
      }
      return;
    }

    if (!roomActive) return;
    handleSenderSignal(msg);
  };

  signal.onClose = () => {
    if (currentRole === "sender" && !isChannelOpen()) {
      resetSession("与国内信令服务器断开，请重新生成房间");
    }
  };

  signal.subscribe(roomTopic);
  setStatus("waiting", `正在检查暗号「${rawCode}」是否可用...`, true);

  // 发送查重探针，650ms 内无现有房主回复则正式占位开房
  setTimeout(() => sendSignal({ type: "room-probe" }), 120);
  probeTimer = setTimeout(() => {
    if (occupied || currentRole !== "sender") return;
    roomActive = true;
    autoRetryCount = 0;
    createRoomBtn.textContent = "房间已开启，等待对方输入暗号...";
    setStatus("waiting", `国内房间已就绪！暗号：${rawCode}（等待接收方连入）`, true);
    showToast("房间已开启，快把暗号告诉对方吧");
  }, APP_CONFIG.probeWaitMs);
}

async function handleSenderSignal(msg) {
  // 响应其他发送方的查重探针
  if (msg.type === "room-probe") {
    sendSignal({ type: "room-occupied", to: msg.from });
    return;
  }

  // 收到接收方的加入请求：严格 1 对 1 锁房
  if (msg.type === "join-request") {
    if (remotePeerId || pendingGuestId) {
      sendSignal({
        type: "room-full",
        to: msg.from,
        reason: "该暗号房间已满（仅支持一对一安全传输）",
      });
      showToast("已自动拦截第 3 台设备的挤入请求");
      return;
    }

    pendingGuestId = msg.from;
    sendSignal({ type: "join-pending", to: pendingGuestId });
    connectRequestBox.classList.remove("hidden");
    setStatus("waiting", "收到对方暗号请求！请下方确认是否同意连接", true);
    return;
  }

  if (msg.type === "join-cancel" && msg.from === pendingGuestId) {
    pendingGuestId = null;
    connectRequestBox.classList.add("hidden");
    setStatus("waiting", `对方取消了连接，继续等待暗号：${sendCodeInput.value.trim()}`, true);
    return;
  }

  if (msg.type === "webrtc-answer" && msg.from === remotePeerId && pc) {
    try {
      await pc.setRemoteDescription(new RTCSessionDescription(msg.sdp));
      await flushPendingIce();
    } catch {}
    return;
  }

  if (msg.type === "webrtc-ice" && msg.from === remotePeerId && pc && msg.candidate) {
    if (pc.remoteDescription) {
      try { await pc.addIceCandidate(new RTCIceCandidate(msg.candidate)); } catch {}
    } else {
      pendingIceCandidates.push(msg.candidate);
    }
  }
}

// 发件方点击“同意连接”：开始创建原生 WebRTC Offer
acceptConnBtn.addEventListener("click", async () => {
  if (!pendingGuestId) return;
  const guestId = pendingGuestId;
  pendingGuestId = null;
  connectRequestBox.classList.add("hidden");
  setStatus("waiting", "已同意连接，正在打通国内点对点加密通道...", true);

  setupPeerConnection(guestId);
  const channel = pc.createDataChannel("anhao-data", { ordered: true });
  attachDataChannel(channel);

  try {
    const offer = await pc.createOffer();
    await pc.setLocalDescription(offer);
    sendSignal({
      type: "webrtc-offer",
      to: guestId,
      sdp: pc.localDescription,
    });
  } catch {
    closePeerConnectionOnly();
    setStatus("error", "创建点对点连接失败，请重试", true);
  }
});

// 发件方点击“拒绝”
