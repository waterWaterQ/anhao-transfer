// ==================== 接收端同步零开销处理 ====================

function triggerDownloadAndFreeMemory(chunks, fileName, mimeType) {
  const blob = new Blob(chunks, { type: mimeType || "application/octet-stream" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();

  setTimeout(() => URL.revokeObjectURL(url), 10000);
}

// 纯同步热路径处理，消除每个分片的 Promise / async 微任务开销
function handleSessionData(rawData) {
  // 1. 收到裸二进制分片（纯同步推入数组，0 拷贝、0 微任务延迟）
  if (rawData instanceof ArrayBuffer || ArrayBuffer.isView(rawData)) {
    if (currentRole !== "receiver" || !isTransferring || !pendingIncomingMeta) return;
    const byteLength = rawData.byteLength;
    receiveChunks.push(rawData);
    receivedBytes += byteLength;
    updateProgress("接收中", receivedBytes, pendingIncomingMeta.size);
    return;
  }

  // 兜底：若极少数环境仍发来 Blob
  if (rawData instanceof Blob) {
    if (currentRole !== "receiver" || !isTransferring || !pendingIncomingMeta) return;
    rawData.arrayBuffer().then((buf) => {
      receiveChunks.push(buf);
      receivedBytes += buf.byteLength;
      updateProgress("接收中", receivedBytes, pendingIncomingMeta.size);
    });
    return;
  }

  const data = parseControlMessage(rawData);
  if (!data) return;

  if (data.type === "idle-timeout") {
    resetSession("已连续 5 分钟无传输操作，自动断开以保护安全");
    showToast("长时间无传输，已自动断开");
    return;
  }

  if (data.type === "text-message") {
    receivedTextContent.textContent = String(data.text || "");
    receivedTextBox.classList.remove("hidden");
    resetIdleTimer();
    showToast("收到一条新文字消息");
    sendJson(activeConn, { type: "text-ack" });
    return;
  }

  if (data.type === "text-ack") {
    resetIdleTimer();
    return;
  }

  if (data.type === "file-offer" && currentRole === "receiver") {
    pendingIncomingMeta = {
      transferId: data.transferId,
      name: String(data.name || "未命名文件"),
      size: Number(data.size) || 0,
      mime: String(data.mime || "application/octet-stream"),
    };
    incomingFileName.textContent = pendingIncomingMeta.name;
    incomingFileSize.textContent = formatBytes(pendingIncomingMeta.size);
    incomingBox.classList.remove("hidden");
    resetIdleTimer();

    if (pendingIncomingMeta.size > APP_CONFIG.largeFileWarnBytes) {
      showToast("收到大文件请求（超过 500 MB），接收期间请勿关闭页面");
    } else {
      showToast("对方发来一个文件，请确认是否接收");
    }
    return;
  }

  if (data.type === "file-accept" && currentRole === "sender") {
    startSendingFileChunks(data.transferId);
    return;
  }

  if (data.type === "file-reject" && currentRole === "sender") {
    clearTransferState(true);
    setStatus("ready", "对方拒绝了该文件，可重新选择文件或发送文字", true);
    resetIdleTimer();
    showToast("对方拒绝了接收该文件");
    return;
  }

  if (data.type === "file-end" && currentRole === "receiver") {
    if (!pendingIncomingMeta || data.transferId !== pendingIncomingMeta.transferId) return;

    const expectedSize = pendingIncomingMeta.size;
    const fileName = pendingIncomingMeta.name;
    const fileMime = pendingIncomingMeta.mime;

    if (receivedBytes !== expectedSize) {
      clearTransferState(true);
      setStatus("error", `文件校验失败（预期 ${expectedSize} 字节，实收 ${receivedBytes} 字节），已清理损坏缓存`, true);
      showToast("文件不完整，已拒绝保存，请让对方重发");
      sendJson(activeConn, { type: "file-error", transferId: data.transferId });
      resetIdleTimer();
      return;
    }

    updateProgress("已完成", expectedSize, expectedSize, true);
    triggerDownloadAndFreeMemory(receiveChunks, fileName, fileMime);
    clearTransferState(false);

    setStatus("ready", `文件「${fileName}」已无损接收并保存！可继续传输`, true);
    showToast(`接收成功：${fileName}`);
    sendJson(activeConn, { type: "file-done", transferId: data.transferId });
    resetIdleTimer();
    return;
  }

  if (data.type === "file-done" && currentRole === "sender") {
    const doneName = selectedFile ? selectedFile.name : "文件";
    clearTransferState(false);
    setStatus("ready", `对方已无损接收「${doneName}」！可继续发送其他文件`, true);
    showToast("对方已成功接收并保存文件！");
    resetIdleTimer();
    return;
  }

  if (data.type === "file-error" && currentRole === "sender") {
    clearTransferState(true);
    setStatus("error", "对方校验文件不完整，请重新点击发送", true);
    showToast("对方校验未通过，请重发");
    resetIdleTimer();
  }
}

// ==================== 发送方创建房间与 1 对 1 锁房 ====================
function createSenderRoom() {
  if (!ensurePeerJsLoaded()) return;

  const rawCode = sendCodeInput.value.trim();
  if (rawCode.length < APP_CONFIG.minCodeLength) {
    showToast(`暗号至少需要 ${APP_CONFIG.minCodeLength} 位`);
    return;
  }

  if (peer) resetSession("正在重新创建房间...");

  currentRole = "sender";
  createRoomBtn.disabled = true;
  sendCodeInput.disabled = true;
  randomCodeBtn.disabled = true;
  setStatus("waiting", `正在创建暗号房间「${rawCode}」...`, true);

  const peerId = codeToPeerId(rawCode);
  peer = new Peer(peerId, {
    config: { iceServers: APP_CONFIG.iceServers },
  });

  connectTimer = setTimeout(() => {
    if (peer && !peer.open) {
      resetSession("连接信令服务器超时（15秒），请检查网络后重试");
      showToast("连接超时，请检查网络或稍后再试");
    }
  }, APP_CONFIG.connectTimeoutMs);

  peer.on("open", () => {
    clearTimeout(connectTimer);
    autoRetryCount = 0;
    createRoomBtn.textContent = "房间已开启，等待对方输入暗号...";
    setStatus("waiting", `房间已就绪！暗号：${rawCode}（等待接收方连入）`, true);
    showToast("房间已开启，快把暗号告诉对方吧");
  });

  peer.on("connection", (conn) => {
    configureFastDataChannel(conn);

    if (activeConn || pendingConn) {
      conn.on("open", () => {
        sendJson(conn, {
          type: "room-full",
          reason: "该暗号房间已满（仅支持一对一安全传输）",
        });
        setTimeout(() => {
          try { conn.close(); } catch {}
        }, 250);
      });
      showToast("已自动拦截第 3 台设备的挤入请求");
      return;
    }

    pendingConn = conn;
    connectRequestBox.classList.remove("hidden");
    setStatus("waiting", "有设备请求连接，请下方确认是否同意", true);

    conn.on("close", () => {
      if (pendingConn === conn) {
        pendingConn = null;
        connectRequestBox.classList.add("hidden");
        setStatus("waiting", `对方取消了连接，继续等待暗号：${sendCodeInput.value.trim()}`, true);
      } else if (activeConn === conn) {
        const wasTransferring = isTransferring;
        activeConn = null;
        clearIdleTimer();
        clearTransferState(true);
        setStatus(
          wasTransferring ? "error" : "waiting",
          wasTransferring
            ? `传输中断：对方已断开连接（暗号：${sendCodeInput.value.trim()} 仍可等待重连）`
            : `对方已断开，房间已解锁，等待新连接（暗号：${sendCodeInput.value.trim()}）`,
          true
        );
        showToast(wasTransferring ? "对方断线，传输已中断" : "对方已断开连接");
      }
    });
  });

  peer.on("error", (err) => {
    clearTimeout(connectTimer);
    if (err.type === "unavailable-id") {
      if (isAutoGeneratedCode && autoRetryCount < 5) {
        autoRetryCount++;
        sendCodeInput.value = generateSafeCode();
        try { peer.destroy(); } catch {}
        peer = null;
        createSenderRoom();
        return;
      }
      resetSession("该暗号正在被别人使用，请换一个暗号或点“换一个”");
      showToast("暗号已被占用，请更换后再试");
      return;
    }

    resetSession(`连接出错（${err.type}），请检查网络后重试`);
    showToast("信令服务连接异常，请稍后重试");
  });
}

