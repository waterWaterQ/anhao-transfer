// ==================== 文件分片高速流控发送（2MB 双缓冲 + 16KB 零拷贝） ====================

function waitForBufferDrain() {
  return new Promise((resolve, reject) => {
    if (!isChannelOpen()) {
      reject(new Error("连接已断开"));
      return;
    }
    if (dc.bufferedAmount <= APP_CONFIG.maxBufferedAmount) {
      resolve();
      return;
    }

    dc.bufferedAmountLowThreshold = APP_CONFIG.lowBufferedAmount;

    let settled = false;
    const cleanup = () => {
      if (dc) {
        dc.removeEventListener("bufferedamountlow", onLow);
        dc.removeEventListener("close", onClose);
      }
      clearInterval(fallbackTimer);
    };

    const onLow = () => {
      if (settled) return;
      settled = true;
      cleanup();
      resolve();
    };

    const onClose = () => {
      if (settled) return;
      settled = true;
      cleanup();
      reject(new Error("连接已断开"));
    };

    dc.addEventListener("bufferedamountlow", onLow);
    dc.addEventListener("close", onClose);

    const fallbackTimer = setInterval(() => {
      if (!isChannelOpen()) {
        onClose();
      } else if (dc.bufferedAmount <= APP_CONFIG.lowBufferedAmount) {
        onLow();
      }
    }, 40);
  });
}

