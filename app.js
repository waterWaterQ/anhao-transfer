// ==================== 数据通道收包处理（纯同步热路径） ====================

function triggerDownloadAndFreeMemory(chunks, fileName, mimeType) {
  const blob = new Blob(chunks, { type: mimeType || "application/octet-stream" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();

  setTimeout(() => URL.revokeObjectURL(url), 10000);
}

function handleChannelMessage(rawData) {
  if (rawData instanceof ArrayBuffer || ArrayBuffer.isView(rawData)) {
    if (currentRole !== "receiver" || !isTransferring || !pendingIncomingMeta) return;
    receiveChunks.push(rawData);
    receivedBytes += rawData.byteLength;
    updateProgress("接收中", receivedBytes, pendingIncomingMeta.size);
    return;
  }

  if (rawData instanceof Blob) {
    if (currentRole !== "receiver" || !isTransferring || !pendingIncomingMeta) return;
    rawData.arrayBuffer().then((buf) => {
      receiveChunks.push(buf);
      receivedBytes += buf.byteLength;
      updateProgress("接收中", receivedBytes, pendingIncomingMeta.size);
    });
    return;
  }

  if (typeof rawData !== "string") return;
  let data;
  try {
    data = JSON.parse(rawData);
  } catch {
    return;
  }
  if (!data || typeof data !== "object") return;

  if (data.type === "idle-timeout") {
    resetSession("已连续 5 分钟无传输操作，自动断开以保护安全");
    showToast("长时间无传输，已自动断开");
    return;
  }

  if (data.type === "text-message") {
    receivedTextContent.textContent = String(data.text || "");
    receivedTextBox.classList.remove("hidden");
    resetIdleTimer();
    showToast("收到一条新文字消息");
    sendControl({ type: "text-ack" });
    return;
  }

  if (data.type === "text-ack") {
    resetIdleTimer();
    return;
  }

  if (data.type === "file-offer" && currentRole === "receiver") {
    pendingIncomingMeta = {
      transferId: data.transferId,
      name: String(data.name || "未命名文件"),
      size: Number(data.size) || 0,
      mime: String(data.mime || "application/octet-stream"),
    };
    incomingFileName.textContent = pendingIncomingMeta.name;
    incomingFileSize.textContent = formatBytes(pendingIncomingMeta.size);
    incomingBox.classList.remove("hidden");
    resetIdleTimer();

    if (pendingIncomingMeta.size > APP_CONFIG.largeFileWarnBytes) {
      showToast("收到大文件请求（超过 500 MB），接收期间请勿关闭页面");
    } else {
      showToast("对方发来一个文件，请确认是否接收");
    }
    return;
  }

  if (data.type === "file-accept" && currentRole === "sender") {
    startSendingFileChunks(data.transferId);
    return;
  }

  if (data.type === "file-reject" && currentRole === "sender") {
    clearTransferState(true);
    setStatus("ready", "对方拒绝了该文件，可重新选择文件或发送文字", true);
    resetIdleTimer();
    showToast("对方拒绝了接收该文件");
    return;
  }

  if (data.type === "file-end" && currentRole === "receiver") {
    if (!pendingIncomingMeta || data.transferId !== pendingIncomingMeta.transferId) return;

    const expectedSize = pendingIncomingMeta.size;
    const fileName = pendingIncomingMeta.name;
    const fileMime = pendingIncomingMeta.mime;

    if (receivedBytes !== expectedSize) {
      clearTransferState(true);
      setStatus("error", `文件校验失败（预期 ${expectedSize} 字节，实收 ${receivedBytes} 字节），已清理损坏缓存`, true);
      showToast("文件不完整，已拒绝保存，请让对方重发");
      sendControl({ type: "file-error", transferId: data.transferId });
      resetIdleTimer();
      return;
    }

    updateProgress("已完成", expectedSize, expectedSize, true);
    triggerDownloadAndFreeMemory(receiveChunks, fileName, fileMime);
    clearTransferState(false);

    setStatus("ready", `文件「${fileName}」已无损接收并保存！可继续传输`, true);
    showToast(`接收成功：${fileName}`);
    sendControl({ type: "file-done", transferId: data.transferId });
    resetIdleTimer();
    return;
  }

  if (data.type === "file-done" && currentRole === "sender") {
    const doneName = selectedFile ? selectedFile.name : "文件";
    const doneSize = selectedFile ? selectedFile.size : 0;
    updateProgress("已完成", doneSize, doneSize, true);
    clearTransferState(false);
    setStatus("ready", `对方已无损接收「${doneName}」！可继续发送其他文件`, true);
    showToast("对方已成功接收并保存文件！");
    resetIdleTimer();
    return;
  }

  if (data.type === "file-error" && currentRole === "sender") {
    clearTransferState(true);
    setStatus("error", "对方校验文件不完整，请重新点击发送", true);
    showToast("对方校验未通过，请重发");
    resetIdleTimer();
  }
}

