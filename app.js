// 解析 ICE 候选类型（host / srflx / prflx / relay）
function extractCandidateType(candidateStr) {
  if (!candidateStr) return "";
  const match = candidateStr.match(/\btyp\s+(host|srflx|prflx|relay)\b/i);
  return match ? match[1].toLowerCase() : "";
}

// ==================== 自带 TURN 配置（本地持久化，零成本开源标配） ====================

function loadCustomTurnConfig() {
  try {
    const raw = localStorage.getItem(APP_CONFIG.turnStorageKey);
    if (!raw) return { urls: "", username: "", credential: "", policy: "all" };
    const parsed = JSON.parse(raw);
    return {
      urls: String(parsed.urls || "").trim(),
      username: String(parsed.username || "").trim(),
      credential: String(parsed.credential || "").trim(),
      policy: parsed.policy === "relay" ? "relay" : "all",
    };
  } catch {
    return { urls: "", username: "", credential: "", policy: "all" };
  }
}

// 解析并自动规范化用户输入的 TURN 地址（自动清理引号/括号，未写协议前缀时自动补全 turn:）
function parseTurnUrls(rawInput) {
  if (!rawInput) return [];
  return rawInput
    .split(/[\s,;]+/)
    .map((item) => item.replace(/^["'\[\(]+|["'\]\)]+$/g, "").trim())
    .filter(Boolean)
    .map((item) => {
      if (/^(stun|turn|turns):/i.test(item)) return item;
      // 兼容直接粘入域名:端口（如 free.expressturn.com:3478）
      if (/^[a-z0-9.-]+(:\d+)?(\?.*)?$/i.test(item)) return `turn:${item}`;
      return "";
    })
    .filter(Boolean);
}

function getRtcConfiguration() {
  const custom = loadCustomTurnConfig();
  const iceServers = [...APP_CONFIG.defaultStunServers];
  let hasTurn = false;

  const urlList = parseTurnUrls(custom.urls);
  if (urlList.length > 0) {
    const turnEntry = { urls: urlList };
    if (custom.username) turnEntry.username = custom.username;
    if (custom.credential) turnEntry.credential = custom.credential;
    iceServers.push(turnEntry);
    hasTurn = urlList.some((u) => /^turns?:/i.test(u));
  }

  // 若未填 TURN 但选了 relay，自动回退 all 并提示，防止空选路
  const iceTransportPolicy = custom.policy === "relay" && hasTurn ? "relay" : "all";
  return { iceServers, iceTransportPolicy, hasTurn };
}

