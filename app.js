// ==================== 安全指纹核对码（由双方真实 DTLS 证书指纹导出） ====================

function extractDtlsFingerprint(sdpText) {
  if (!sdpText) return "";
  const match = sdpText.match(/a=fingerprint:sha-256\s+([0-9A-Fa-f:]+)/i);
  return match ? match[1].toUpperCase() : "";
}

function computeShortVerifyCode(localSdp, remoteSdp) {
  const fp1 = extractDtlsFingerprint(localSdp);
  const fp2 = extractDtlsFingerprint(remoteSdp);
  if (!fp1 || !fp2) return "";
  // 按字典序拼接，确保发送方与接收方计算结果 100% 相同
  const combined = [fp1, fp2].sort().join("|");
  let h = 0x811c9dc5;
  for (let i = 0; i < combined.length; i++) {
    h ^= combined.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  const chars = APP_CONFIG.codeAlphabet;
  const u = h >>> 0;
  const c1 = chars[u % chars.length];
  const c2 = chars[Math.floor(u / 32) % chars.length];
  const c3 = chars[Math.floor(u / 1024) % chars.length];
  const c4 = chars[Math.floor(u / 32768) % chars.length];
  return `${c1}${c2}-${c3}${c4}`;
}

