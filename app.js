// ==================== 接收方输入暗号加入房间 ====================
function joinReceiverRoom() {
  if (!ensurePeerJsLoaded()) return;

  const rawCode = receiveCodeInput.value.trim();
  if (rawCode.length < APP_CONFIG.minCodeLength) {
    showToast(`请输入至少 ${APP_CONFIG.minCodeLength} 位的暗号`);
    return;
  }

  if (peer) resetSession("正在尝试连接...");

  currentRole = "receiver";
  joinRoomBtn.disabled = true;
  receiveCodeInput.disabled = true;
  setStatus("waiting", `正在寻找暗号「${rawCode}」对应的发送方...`, true);

  peer = new Peer({
    config: { iceServers: APP_CONFIG.iceServers },
  });

  connectTimer = setTimeout(() => {
    if (!activeConn) {
      resetSession("连接超时（15秒）：请检查暗号是否正确，或尝试切换同一 Wi-Fi");
      showToast("连接超时，未收到对方响应");
    }
  }, APP_CONFIG.connectTimeoutMs);

  peer.on("open", () => {
    const targetPeerId = codeToPeerId(rawCode);
    const conn = peer.connect(targetPeerId, {
      reliable: true,
      serialization: "raw",
    });

    conn.on("open", () => {
      configureFastDataChannel(conn);
      setStatus("waiting", "已找到发送方，等待对方点击「同意连接」...", true);
    });

    conn.on("data", async (rawData) => {
      if (!activeConn) {
        const msg = parseControlMessage(rawData);
        if (msg) {
          if (msg.type === "room-full") {
            clearTimeout(connectTimer);
            resetSession(msg.reason || "该暗号房间已满（仅支持一对一传输）");
            showToast("房间已满，无法加入");
            return;
          }
          if (msg.type === "connect-rejected") {
            clearTimeout(connectTimer);
            resetSession(msg.reason || "发送方拒绝了你的连接请求");
            showToast("对方拒绝了连接请求");
            return;
          }
          if (msg.type === "connect-accepted") {
            clearTimeout(connectTimer);
            activeConn = conn;
            configureFastDataChannel(activeConn);
            const routeInfo = await detectRouteType(activeConn);
            setStatus(
              "ready",
              `已建立一对一加密直连 ${routeInfo ? `｜ ${routeInfo}` : "｜ 等待对方发送"}`,
              true
            );
            resetIdleTimer();
            showToast("配对成功！等待发送方传文件");
            return;
          }
        }
      }

      if (activeConn === conn) {
        handleSessionData(rawData);
      }
    });

    conn.on("close", () => {
      if (currentRole === "receiver") {
        const wasTransferring = isTransferring;
        resetSession(wasTransferring ? "传输中断：发送方已断开连接，已清理残余缓存" : "与发送方的连接已断开");
        if (wasTransferring) showToast("发送方断线，传输已中断");
      }
    });

    conn.on("error", () => {
      clearTimeout(connectTimer);
      resetSession("点对点直连失败，请检查网络或尝试切换同一 Wi-Fi");
    });
  });

  peer.on("error", (err) => {
    clearTimeout(connectTimer);
    if (err.type === "peer-unavailable") {
      resetSession("未找到该暗号对应的发送方，请检查是否输错，或确认对方已开启房间");
      showToast("未找到该暗号，请核对后再试");
      return;
    }

    resetSession(`连接异常（${err.type}），请检查网络后重试`);
    showToast("连接异常，请稍后再试");
  });
}

